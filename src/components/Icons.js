/**
 * İmza detay: 5 yapraklı zorluk göstergesi (1.5px stroke)
 */
export const DifficultyLeaves = ({ level = 1, max = 5 } = {}) => {
  let leavesHtml = '';
  for (let i = 1; i <= max; i++) {
    const isFilled = i <= level;
    leavesHtml += `
      <span class="difficulty-leaf ${isFilled ? 'is-active' : 'is-muted'}" title="Zorluk: ${level} / ${max}">
        <svg xmlns="http://www.w3.org/2000/svg" width="13" height="13" viewBox="0 0 24 24" fill="${isFilled ? 'currentColor' : 'none'}" stroke="currentColor" stroke-width="1.5" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">
          <path d="M11 20A7 7 0 0 1 9.8 6.1C15.5 5 17 4.48 19 2c1 2 2 4.18 2 8 0 5.5-4.78 10-10 10Z"/>
          <path d="M2 21c0-3 1.85-5.36 5.08-6C9.5 14.52 12 13 13 12"/>
        </svg>
      </span>
    `;
  }
  return `<span class="difficulty-leaves-wrapper" aria-label="Zorluk düzeyi ${level} / ${max}">${leavesHtml}</span>`;
};

